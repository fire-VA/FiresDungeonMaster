        /// <summary>Cycle the module ROLE (SectionRole int) forward/back. Owner-persisted.</summary>
        public void CycleRole(int dir)
        {
            int count = System.Enum.GetValues(typeof(FiresDungeonMaster.Sections.SectionRole)).Length;
            if (dir == 0) dir = 1;
            Role = (Role + (dir > 0 ? 1 : count - 1)) % count;
            ClaimOwnershipIfNeeded();
            SaveToZDO();
            ShowMessage($"Role: <color=yellow>{RoleName()}</color>");
        }

        /// <summary>
        /// Cycle the dungeon-type name through the DISTINCT existing dungeon-type names in the shared library,
        /// plus a leading "(unset)" slot. Use SetDungeonType for a brand-new name (the Fires input field path).
        /// </summary>
        public void CycleDungeonType(int dir)
        {
            var names = new System.Collections.Generic.List<string> { "" };
            foreach (var n in FootprintLibraryAccess.DistinctDungeonTypes())
                if (!names.Contains(n)) names.Add(n);

            int idx = names.FindIndex(n => string.Equals(n, DungeonType ?? "", System.StringComparison.OrdinalIgnoreCase));
            if (idx < 0) idx = 0;
            if (dir == 0) dir = 1;
            idx = (idx + (dir > 0 ? 1 : names.Count - 1)) % names.Count;
            SetDungeonType(names[idx]);
        }

        /// <summary>Set the dungeon-type name directly (e.g. from the Fires input field). Owner-persisted.</summary>
        public void SetDungeonType(string name)
        {
            DungeonType = name ?? "";
            ClaimOwnershipIfNeeded();
            SaveToZDO();
            ShowMessage($"Dungeon Type: <color=yellow>{(string.IsNullOrEmpty(DungeonType) ? "(unset)" : DungeonType)}</color>");
        }

        /// <summary>
        /// Surface the 4 per-face edge-tag ints into the P1 SectionBlueprint EdgeTags shape
        /// (Dictionary<string,List<string>>, lowercase north/south/east/west keys, single-element lists).
        /// A Wall face is emitted as an EMPTY list so SectionSchema writes no #fdm_edge_{face} line for it.
        /// This is what P4 SAVE reads to populate the blueprint.
        /// </summary>
        public System.Collections.Generic.Dictionary<string, System.Collections.Generic.List<string>> ToSectionEdgeTags()
        {
            var d = new System.Collections.Generic.Dictionary<string, System.Collections.Generic.List<string>>
            {
                { "north", FaceList(EdgeTagN) },
                { "south", FaceList(EdgeTagS) },
                { "east",  FaceList(EdgeTagE) },
                { "west",  FaceList(EdgeTagW) }
            };
            return d;
        }

        private static System.Collections.Generic.List<string> FaceList(EdgeTag t)
        {
            var list = new System.Collections.Generic.List<string>();
            if (t != EdgeTag.Wall) list.Add(EdgeTagWord(t));
            return list;
        }

        /// <summary>
        /// P4 SAVE bridge: build the SectionBlueprint EdgeTags dictionary (lowercase north/south/east/west keys,
        /// single-element lists; Wall => empty list). Reads the ZDO first so a non-owner's view is current, then
        /// maps the P3 EdgeTag enum onto the lowercase tag vocabulary. This is the member SectionCapture requires.
        /// </summary>
        public System.Collections.Generic.Dictionary<string, System.Collections.Generic.List<string>> BuildEdgeTagsForBlueprint()
        {
            SyncEdgeTagsFromZDO();
            return ToSectionEdgeTags();
        }

        private void SyncEdgeTagsFromZDO()
        {
            if (m_nview == null) return;
            var zdo = m_nview.GetZDO();
            if (zdo == null) return;
            EdgeTagN = (EdgeTag)zdo.GetInt(HASH_EDGE_N, (int)EdgeTagN);
            EdgeTagE = (EdgeTag)zdo.GetInt(HASH_EDGE_E, (int)EdgeTagE);
            EdgeTagS = (EdgeTag)zdo.GetInt(HASH_EDGE_S, (int)EdgeTagS);
            EdgeTagW = (EdgeTag)zdo.GetInt(HASH_EDGE_W, (int)EdgeTagW);
        }

        private void ClaimOwnershipIfNeeded()
        {
            // SaveToZDO no-ops unless we own the ZDO; an admin editing a non-owned footprint must claim it first.
            if (m_nview != null && m_nview.IsValid() && !m_nview.IsOwner())
                m_nview.ClaimOwnership();
        }

