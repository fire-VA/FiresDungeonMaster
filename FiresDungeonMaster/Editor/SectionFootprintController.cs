        /// <summary>
        /// Checks if a world point is inside this footprint box, optionally expanded by a margin (metres). The box is
        /// BOTTOM-ANCHORED: the footprint origin is the FLOOR (local Y=0) and the box rises to Y=BoxSize.y (the bake
        /// normalizes the frame's min.y to 0), so the vertical test is [0, BoxSize.y], NOT the centered [-half, +half]
        /// it used to be — that old range put half the test volume UNDERGROUND and excluded the upper half of the
        /// visible box, so a right-click aimed high in the box fell outside and the claim declined (companion menu bug).
        /// </summary>
        public bool ContainsPoint(Vector3 worldPoint, float margin = 0f)
        {
            Vector3 localPoint = transform.InverseTransformPoint(worldPoint);
            float hx = BoxSize.x * 0.5f + margin, hz = BoxSize.z * 0.5f + margin;
            return localPoint.x >= -hx && localPoint.x <= hx &&
                   localPoint.y >= -margin && localPoint.y <= BoxSize.y + margin &&
                   localPoint.z >= -hz && localPoint.z <= hz;
        }

        /// <summary>
        /// Delete every build piece / prop / furniture / vegetation / item-drop INSIDE this footprint box (NOT
        /// players, monsters, or another footprint) — called when the box itself is removed, so the whole staging
        /// area clears in one action instead of piece-by-piece. Server-auth: claims each ZDO then ZNetScene.Destroy.
        /// </summary>
        public static void DestroyContents(SectionFootprintController fp)
        {
            var scene = ZNetScene.instance;
            if (fp == null || scene == null || scene.m_instances == null) return;

            var victims = new List<GameObject>();
            foreach (var kv in scene.m_instances)
            {
                var nv = kv.Value;
                if (nv == null) continue;
                var go = nv.gameObject;
                if (go == null || go == fp.gameObject) continue;
                if (go.GetComponentInParent<SectionFootprintController>() != null) continue;   // the box or any other box
                if (go.GetComponent<Player>() != null) continue;
                var ch = go.GetComponent<Character>();
                if (ch != null && go.GetComponent<MonsterAI>() != null) continue;               // live enemies aren't content
                if (!fp.ContainsPoint(go.transform.position)) continue;
                victims.Add(go);
            }

            int n = 0;
            foreach (var go in victims)
            {
                try
                {
                    var nv = go.GetComponent<ZNetView>();
                    if (nv == null || !nv.IsValid()) continue;
                    nv.ClaimOwnership();
                    scene.Destroy(go);
                    n++;
                }
                catch { }
            }
            if (n > 0) Debug.Log($"[FiresDungeonMaster] footprint removed — cleared {n} contained object(s).");
        }

        // When a footprint box is DELETED (ZNetScene.Destroy = the permanent-delete path; stream-out uses a separate
        // pool path), take its contents with it — but only when the local player is right there (a proximity guard so
        // a far stream-out, if it ever routed through here, can never wipe a build). Auto-discovered by FiresMod PatchAll.
        [HarmonyPatch(typeof(ZNetScene), nameof(ZNetScene.Destroy), new[] { typeof(GameObject) })]
        private static class Destroy_FootprintContents_Patch
        {
            private static void Prefix(GameObject go)
            {
                if (go == null) return;
                var fp = go.GetComponent<SectionFootprintController>();
                if (fp == null) return;
                var p = Player.m_localPlayer;
                if (p == null) return;                                                          // dedi/server: the removing client already cleared contents
                if ((p.transform.position - fp.transform.position).sqrMagnitude > 60f * 60f) return;  // far = not a hand-remove
                DestroyContents(fp);
            }
        }

        /// <summary>
        /// True when the local player is inside or right beside any placed footprint box — the dungeon STAGING AREA.
        /// The Core companion whistle (Shift+RightClick) registers this as its suppressor so a Shift+RightClick near a
        /// box edits/opens it instead of summoning a companion into the build.
        /// </summary>
        public static bool IsPlayerInStagingArea()
        {
            var p = Player.m_localPlayer;
            if (p == null) return false;
            Vector3 pos = p.transform.position;
            var active = Active;
            for (int i = 0; i < active.Count; i++)
            {
                var fp = active[i];
                if (fp == null) continue;
                if (fp.ContainsPoint(pos, 6f)) return true;
                Vector3 d = fp.transform.position - pos; d.y = 0f;
                if (d.sqrMagnitude < 18f * 18f) return true;
            }
            return false;
        }

