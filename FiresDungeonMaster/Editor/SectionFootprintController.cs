        public static int FaceIndexOf(MarkerHit face)
        {
            switch (face) { case MarkerHit.North: return 0; case MarkerHit.East: return 1; case MarkerHit.South: return 2; case MarkerHit.West: return 3; default: return -1; }
        }

        /// <summary>True when this face is the designated main entrance/exit.</summary>
        public bool IsEntranceFace(MarkerHit face) => EntranceFace >= 0 && EntranceFace == FaceIndexOf(face);

        /// <summary>
        /// Mark one outer face as the dungeon MAIN ENTRANCE/EXIT (the "first room" generation starts from). Toggles
        /// off if it's already the entrance. Owner-persisted. Warns if the face isn't a connecting opening.
        /// </summary>
        public void SetEntranceFace(MarkerHit face)
        {
            int idx = FaceIndexOf(face);
            if (idx < 0) return;
            EntranceFace = (EntranceFace == idx) ? -1 : idx;
            ClaimOwnershipIfNeeded();
            SaveToZDO();
            RefreshEdgeMarkerColors();
            RebuildGuides();
            if (EntranceFace < 0) ShowMessage("Main entrance: <color=yellow>none</color>");
            else ShowMessage($"Main entrance: <color=yellow>{FaceName(face)}</color>" +
                             (IsDoorwayFace(idx) ? "" : "  <color=#ffcc88>(tip: make this face a Doorway or Open)</color>"));
        }

        /// <summary>Set ONE face's tag directly (the edge context-menu path). Owner-persisted + recolors that edge.</summary>
        public void SetEdgeTag(MarkerHit face, EdgeTag tag)
        {
            switch (face)
            {
                case MarkerHit.North: EdgeTagN = tag; break;
                case MarkerHit.East:  EdgeTagE = tag; break;
                case MarkerHit.South: EdgeTagS = tag; break;
                case MarkerHit.West:  EdgeTagW = tag; break;
                default: return;
            }
            ClaimOwnershipIfNeeded();
            SaveToZDO();
            RefreshEdgeMarkerColors();
            RebuildSnapPoints();
            RebuildGuides();
            ShowMessage($"{FaceName(face)} edge: <color=yellow>{EdgeTagWord(tag)}</color>");
        }

        /// <summary>Capture every object inside the footprint and save it as a reusable section (.blueprint). The
        /// name (display + id key) and optional notes come from the Save dialog; null falls back to an auto name.</summary>
