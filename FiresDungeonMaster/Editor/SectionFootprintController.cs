        #region ZDO persistence

        private void LoadFromZDO()
        {
            if (m_nview == null) return;
            var zdo = m_nview.GetZDO();
            if (zdo == null) return;

            float sx = zdo.GetFloat(HASH_SIZE_X, BoxSize.x);
            float sy = zdo.GetFloat(HASH_SIZE_Y, BoxSize.y);
            float sz = zdo.GetFloat(HASH_SIZE_Z, BoxSize.z);
            BoxSize = new Vector3(sx, sy, sz);

            FootprintCellsX = zdo.GetInt(HASH_CELLS_X, FootprintCellsX);
            FootprintCellsZ = zdo.GetInt(HASH_CELLS_Z, FootprintCellsZ);
            Stories = zdo.GetInt(HASH_STORIES, Stories);
            Role = zdo.GetInt(HASH_ROLE, Role);
            DungeonType = zdo.GetString(HASH_DUNGEONTYPE, DungeonType);

            EdgeTagN = (EdgeTag)zdo.GetInt(HASH_EDGE_N, (int)EdgeTagN);
            EdgeTagE = (EdgeTag)zdo.GetInt(HASH_EDGE_E, (int)EdgeTagE);
            EdgeTagS = (EdgeTag)zdo.GetInt(HASH_EDGE_S, (int)EdgeTagS);
            EdgeTagW = (EdgeTag)zdo.GetInt(HASH_EDGE_W, (int)EdgeTagW);
            EntranceFace = zdo.GetInt(HASH_ENTRANCE, EntranceFace);

            ApplyTriggerBounds();
        }

        private void SaveToZDO()
        {
            if (m_nview == null || !m_nview.IsOwner()) return;
            var zdo = m_nview.GetZDO();
            if (zdo == null) return;

            zdo.Set(HASH_SIZE_X, BoxSize.x);
            zdo.Set(HASH_SIZE_Y, BoxSize.y);
            zdo.Set(HASH_SIZE_Z, BoxSize.z);
            zdo.Set(HASH_CELLS_X, FootprintCellsX);
            zdo.Set(HASH_CELLS_Z, FootprintCellsZ);
            zdo.Set(HASH_STORIES, Stories);
            zdo.Set(HASH_ROLE, Role);
            zdo.Set(HASH_DUNGEONTYPE, DungeonType ?? "");
            zdo.Set(HASH_EDGE_N, (int)EdgeTagN);
            zdo.Set(HASH_EDGE_E, (int)EdgeTagE);
            zdo.Set(HASH_EDGE_S, (int)EdgeTagS);
            zdo.Set(HASH_EDGE_W, (int)EdgeTagW);
            zdo.Set(HASH_ENTRANCE, EntranceFace);
        }

