        // WYSIWYG guide walls. (Re)materialize the translucent wall/door/window panel on every face per its tag, and
        // hand the orb off to the wall: a materialized face (Wall/Doorway/Window/Back) hides its edge orb (the panel
        // is now the interaction point), while an Open face keeps its orb. Rebuilt on every tag/size/load change.
        // Skipped on the placement ghost (its solid guide colliders on 'static_solid' would fight the build-place ray)
        // and headless (SectionGuideWalls builds meshes/colliders — client-only).
        private void RebuildGuides()
        {
            if (IsClientOnly()) return;
            if (Player.IsPlacementGhost(gameObject)) { SectionGuideWalls.Log($"skip: placement ghost fp='{name}'"); return; }

            if (m_guideRoot == null)
            {
                m_guideRoot = new GameObject("SectionGuides");
                m_guideRoot.transform.SetParent(transform, false);
                m_guideRoot.transform.localPosition = Vector3.zero;
                m_guideRoot.transform.localRotation = Quaternion.identity;
                m_guideRoot.transform.localScale = Vector3.one;
            }

            SectionGuideWalls.Log($"RebuildGuides fp='{name}' fpPos={transform.position} fpScale={transform.lossyScale} box={BoxSize} " +
                $"markersBuilt={m_markersBuilt} guideRoot(local={m_guideRoot.transform.localPosition} lossyScale={m_guideRoot.transform.lossyScale} world={m_guideRoot.transform.position})");

            try
            {
                SectionGuideWalls.Clear(m_guideRoot.transform);
                int panels = 0;
                for (int face = 0; face < FaceCount; face++)
                {
                    EdgeTag t = GetEdgeTag(face);
                    int segs = SectionGuideWalls.BuildFace(m_guideRoot.transform, face, BoxSize, t);
                    if (segs > 0) panels++;
                    var orb = MarkerObjectForFace(face);
                    if (orb != null) orb.SetActive(!SectionGuideWalls.FaceHasPanel(t));
                    SectionGuideWalls.Log($"  face={FaceNames[face]} tag={t} segs={segs} orb={(orb != null ? (orb.activeSelf ? "SHOWN" : "hidden") : "null(not-baked)")}");
                }
                SectionGuideWalls.LogVerify(m_guideRoot.transform, panels);
            }
            catch (System.Exception ex)
            {
                Debug.LogError($"[GUIDE-DBG] RebuildGuides EXCEPTION (guides skipped, footprint unaffected): {ex}");
            }
        }

