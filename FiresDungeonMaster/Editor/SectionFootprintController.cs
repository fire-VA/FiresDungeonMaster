        #region Edge tags + snapping (P5)

        // Stable face ordering used everywhere snapping iterates: N, E, S, W.
        // Index maps to GetEdgeTag/SetEdgeTag/EdgeLocalNormal/EdgeLocalMidpoint.
        public const int FaceCount = 4;
        public static readonly string[] FaceNames = { "north", "east", "south", "west" };

        public EdgeTag GetEdgeTag(int face)
        {
            switch (face)
            {
                case 0: return EdgeTagN;
                case 1: return EdgeTagE;
                case 2: return EdgeTagS;
                default: return EdgeTagW;
            }
        }

        /// <summary>Set a face tag, persist (owner only), and refresh the snap points. P3 cycling consumers can call this.</summary>
        public void SetEdgeTag(int face, EdgeTag tag)
        {
            switch (face)
            {
                case 0: EdgeTagN = tag; break;
                case 1: EdgeTagE = tag; break;
                case 2: EdgeTagS = tag; break;
                default: EdgeTagW = tag; break;
            }
            if (m_nview != null && m_nview.IsValid() && m_nview.IsOwner())
                SaveToZDO();
            RebuildSnapPoints();
            RebuildGuides();
        }

        /// <summary>A face is snap-eligible when its tag is a connecting opening (Doorway or Open).</summary>
        public static bool IsDoorway(EdgeTag tag) => tag == EdgeTag.Doorway || tag == EdgeTag.Open;
        public bool IsDoorwayFace(int face) => IsDoorway(GetEdgeTag(face));

        /// <summary>Outward unit normal of a face in LOCAL space. North=+Z, East=+X, South=-Z, West=-X.</summary>
        public static Vector3 EdgeLocalNormal(int face)
        {
            switch (face)
            {
                case 0: return Vector3.forward;  // north +Z
                case 1: return Vector3.right;    // east  +X
                case 2: return Vector3.back;     // south -Z
                default: return Vector3.left;    // west  -X
            }
        }

        /// <summary>Midpoint of a face in LOCAL space (box-centered origin). Y at the box vertical center.</summary>
        public Vector3 EdgeLocalMidpoint(int face)
        {
            Vector3 h = BoxSize / 2f;
            switch (face)
            {
                case 0: return new Vector3(0f, 0f,  h.z);  // north
                case 1: return new Vector3( h.x, 0f, 0f);  // east
                case 2: return new Vector3(0f, 0f, -h.z);  // south
                default: return new Vector3(-h.x, 0f, 0f); // west
            }
        }

        /// <summary>Face midpoint in WORLD space (respects transform rotation/position).</summary>
        public Vector3 EdgeWorldMidpoint(int face) => transform.TransformPoint(EdgeLocalMidpoint(face));

        /// <summary>Face outward normal in WORLD space (rotation only).</summary>
        public Vector3 EdgeWorldNormal(int face) => transform.rotation * EdgeLocalNormal(face);

        // Valheim's floor-tile pitch: wood/stone 2x2 floor tiles, walls, and most build pieces snap on a 2m grid.
        // Laying snap points at this pitch lets vanilla pieces drop cleanly into the build space and to each other.
        public const float SnapPitch = 2f;
        // Cap grid lines per axis so a 200m max-size box can't spawn ~10k snap-point GameObjects.
        private const int MaxSnapLines = 33;

        /// <summary>
        /// (Re)build the vanilla 'snappoint'-tagged child markers as a 2m GRID across the floor plane plus the
        /// face midpoints. They are emitted as DIRECT children of this footprint transform — vanilla
        /// Piece.GetSnapPoints (assembly_valheim/Piece.cs:268-276) enumerates only direct children by tag and does
        /// NOT recurse, so nesting them under the FootprintTagMarkers holder would make them invisible to
        /// Player.FindClosestSnapPoints. With the markers as direct children, vanilla's snap assist finds them so
        /// floor tiles + walls + any build piece snap into the build space; FootprintSnapController layers the
        /// full doorway position+rotation alignment on top for section-to-section layout.
        ///
        /// The grid is driven off BoxSize at the SnapPitch, so it rebuilds whenever the box is resized. Returns
        /// EARLY on a headless/dedicated server (no GameObject churn) — snap points only matter to the client
        /// placement ghost. The edge tags themselves still persist server-side via SaveToZDO.
        /// </summary>
        public void RebuildSnapPoints()
        {
            if (IsClientOnly()) return;

            for (int i = m_snapMarkers.Count - 1; i >= 0; i--)
            {
                if (m_snapMarkers[i] != null) Destroy(m_snapMarkers[i]);
            }
            m_snapMarkers.Clear();

            Vector3 half = BoxSize / 2f;
            // Grid points at SnapPitch across the floor plane (Y=0, the floor top). Count is inclusive of both
            // edges: a 8m span at 2m pitch yields lines at -4,-2,0,2,4 (5 points/axis = nx*nz floor nodes).
            int nx = Mathf.Clamp(Mathf.RoundToInt(BoxSize.x / SnapPitch) + 1, 2, MaxSnapLines);
            int nz = Mathf.Clamp(Mathf.RoundToInt(BoxSize.z / SnapPitch) + 1, 2, MaxSnapLines);
            for (int ix = 0; ix < nx; ix++)
            {
                float x = Mathf.Lerp(-half.x, half.x, nx == 1 ? 0.5f : (float)ix / (nx - 1));
                for (int iz = 0; iz < nz; iz++)
                {
                    float z = Mathf.Lerp(-half.z, half.z, nz == 1 ? 0.5f : (float)iz / (nz - 1));
                    CreateSnapPointChild(new Vector3(x, 0f, z), $"SnapGrid_{ix}_{iz}");
                }
            }

            // Face-midpoint snaps at the box vertical center too, so an edge wall/doorway piece can grab the face.
            for (int face = 0; face < FaceCount; face++)
                CreateSnapPointChild(EdgeLocalMidpoint(face), $"SnapEdge_{FaceNames[face]}");
        }

        // Mirrors InfinityHammer.Snapping.CreateSnapPoint: an inactive GameObject on the 'piece' layer,
        // tagged 'snappoint', as a DIRECT child of the footprint at a local position. Tracked in
        // m_snapMarkers so RebuildSnapPoints clears only these and never the wireframe renderer.
        private void CreateSnapPointChild(Vector3 localPos, string name)
        {
            var go = new GameObject(name);
            int pieceLayer = LayerMask.NameToLayer("piece");
            go.layer = pieceLayer >= 0 ? pieceLayer : 0;
            go.tag = "snappoint";
            go.transform.SetParent(transform, false);
            go.transform.localPosition = localPos;
            go.transform.localRotation = Quaternion.identity;
            go.SetActive(false);
            m_snapMarkers.Add(go);
        }

