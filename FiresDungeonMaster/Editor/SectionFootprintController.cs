        /// <summary>Cycle one face's tag forward (Wall->Doorway->Open->Window->Back->Left->Right->Wall). Owner-persisted.</summary>
        public void CycleEdgeTag(MarkerHit face, int dir)
        {
            int count = System.Enum.GetValues(typeof(EdgeTag)).Length;
            if (dir == 0) dir = 1;
            switch (face)
            {
                case MarkerHit.North: EdgeTagN = Step(EdgeTagN, dir, count); break;
                case MarkerHit.East:  EdgeTagE = Step(EdgeTagE, dir, count); break;
                case MarkerHit.South: EdgeTagS = Step(EdgeTagS, dir, count); break;
                case MarkerHit.West:  EdgeTagW = Step(EdgeTagW, dir, count); break;
                default: return;
            }
            ClaimOwnershipIfNeeded();
            SaveToZDO();
            RefreshEdgeMarkerColors();
            RebuildGuides();
            ShowMessage($"{FaceName(face)} edge: <color=yellow>{TagOf(face)}</color>");
        }

