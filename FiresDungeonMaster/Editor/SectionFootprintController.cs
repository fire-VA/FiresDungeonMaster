    /// <summary>
    /// SectionFootprintController — the hammer-placeable dungeon-section FOOTPRINT box (the "blank room").
    ///
    /// This is a stripped clone of FiresCore.Utilities.EnvironmentBoxController: it keeps ONLY the parts a
    /// footprint editor needs — a scalable trigger box, a runtime wireframe box mesh, ZDO persistence, a Hoverable
    /// label, and an Interactable stub — and drops every environment/weather/biome/skybox/wind/time/enclosure
    /// override the env-box carried. The wireframe VISUAL is generated by this controller at runtime (the baked
    /// prefab carries no mesh), exactly like the env box.
    ///
    /// ZDO fields (P2): box size (x/y/z), footprint cells X, footprint cells Z, story height, a module ROLE int,
    /// and a DUNGEON-TYPE name string. P3 adds the 6 edge-tag ints + the Shift+Scroll size scaler; P2 is
    /// place / persist / hover only — Interact() is a no-op.
    ///
    /// Dedi-safe: IsClientOnly() (no graphics device) gates EVERY renderer/mesh/material touch. The ZNetView +
    /// ZDO logic still runs headless so placed footprints persist server-side.
    /// </summary>
    public class SectionFootprintController : MonoBehaviour, Hoverable, Interactable
    {
        #region Dedi guard

        // True on a headless/dedicated server (no graphics device). The footprint ZNetView still instantiates
        // there for ZDO persistence, but every mesh/material/renderer path must early-return or it NREs.
        private static bool IsClientOnly()
            => SystemInfo.graphicsDeviceType == GraphicsDeviceType.Null;

        #endregion

        #region Serialized footprint settings

        [Header("Box")]
        public Vector3 BoxSize = new Vector3(8f, 4f, 8f);
        public Vector3 MinSize = new Vector3(2f, 2f, 2f);
        public Vector3 MaxSize = new Vector3(200f, 100f, 200f);

        [Header("Footprint (P2 defaults)")]
        // Footprint measured in dungeon grid cells on the X / Z axes.
        public int FootprintCellsX = 1;
        public int FootprintCellsZ = 1;
        // Story height (number of stacked floors this section occupies).
        public int Stories = 1;
        // Module role — an int tag (start / hall / junction / cap / boss / ...). Cycled in P3; display-only in P2.
        public int Role = 0;
        // Dungeon-type name string: every section sharing this name generates into the same dungeon.
        public string DungeonType = "";

        #endregion

        #region Runtime state

        private ZNetView m_nview;
        private BoxCollider m_trigger;

        // ZDO hash codes (footprint-specific keys — disjoint from the env box's envbox_* keys).
        private static readonly int HASH_SIZE_X = "footprint_sx".GetStableHashCode();
        private static readonly int HASH_SIZE_Y = "footprint_sy".GetStableHashCode();
        private static readonly int HASH_SIZE_Z = "footprint_sz".GetStableHashCode();
        private static readonly int HASH_CELLS_X = "footprint_cx".GetStableHashCode();
        private static readonly int HASH_CELLS_Z = "footprint_cz".GetStableHashCode();
        private static readonly int HASH_STORIES = "footprint_stories".GetStableHashCode();
        private static readonly int HASH_ROLE = "footprint_role".GetStableHashCode();
        private static readonly int HASH_DUNGEONTYPE = "footprint_dtype".GetStableHashCode();

        // P3 edge-tag ZDO keys (one int per face = the EdgeTag enum value). Disjoint from the P2 footprint_* keys.
        private static readonly int HASH_EDGE_N = "footprint_edge_n".GetStableHashCode();
        private static readonly int HASH_EDGE_E = "footprint_edge_e".GetStableHashCode();
        private static readonly int HASH_EDGE_S = "footprint_edge_s".GetStableHashCode();
        private static readonly int HASH_EDGE_W = "footprint_edge_w".GetStableHashCode();
        private static readonly int HASH_ENTRANCE = "footprint_entrance".GetStableHashCode();

        // P3 per-face tag (persisted as the int above). Default Wall = the un-tagged solid face.
        public EdgeTag EdgeTagN = EdgeTag.Wall;
        public EdgeTag EdgeTagE = EdgeTag.Wall;
        public EdgeTag EdgeTagS = EdgeTag.Wall;
        public EdgeTag EdgeTagW = EdgeTag.Wall;

        // Which outer face (0=N,1=E,2=S,3=W) is the dungeon's MAIN ENTRANCE/EXIT — the "first room" generation starts
        // from (the mandatory m_entrance). -1 = none set. Persisted; recorded into the saved blueprint/set.
        public int EntranceFace = -1;

        // Baked visual gizmos (bound from the prefab's "FootprintTagMarkers" holder). Bound in BindBakedVisual(),
        // repositioned/rescaled in UpdateMarkerTransforms / LateUpdate. The baked children are the single source of
        // truth — the controller never builds parallel geometry.
        private Transform m_wireBox;
        private GameObject m_markerRoot;
        private GameObject m_markerFloor;
        // WYSIWYG guide walls holder (client-only): the translucent wall/door/window panels materialized per face.
        private GameObject m_guideRoot;
        private GameObject m_markerN, m_markerE, m_markerS, m_markerW, m_markerCenter;
        private MeshRenderer m_rendN, m_rendE, m_rendS, m_rendW, m_rendCenter;
        private bool m_markersBuilt;
        private bool m_baseTinted;

        // P5: runtime 'snappoint'-tagged DIRECT children for doorway edges (client-only). Held so clearing only
        // touches our markers, never the wireframe renderer that lives on this same GameObject.
        private readonly System.Collections.Generic.List<GameObject> m_snapMarkers = new System.Collections.Generic.List<GameObject>();

        // Live, streamed-in footprints (client-only). The context-menu marker hit-tester iterates this to ray-test
        // the 5 spheres of every placed footprint without colliders or a scene scan. Registered in Awake, dropped
        // in OnDestroy.
        internal static readonly System.Collections.Generic.List<SectionFootprintController> Active =
            new System.Collections.Generic.List<SectionFootprintController>();

        #endregion

        #region P3 EdgeTag enum

        /// <summary>
        /// Per-edge tag vocabulary. The int value is the persisted ZDO contract (footprint_edge_n/e/s/w).
        /// Surfaced into SectionBlueprint.EdgeTags (lowercase string vocab) by ToSectionEdgeTags(); a Doorway/Open
        /// face becomes a RoomConnection in P6.
        /// </summary>
        public enum EdgeTag
        {
            Wall = 0,     // solid face, no connection
            Doorway = 1,  // door-sized opening; mates another Doorway in P6
            Open = 2,     // fully-open face (large opening / arch)
            Window = 3,   // decorative opening, NOT a connection
            Back = 4,     // dead-end / back wall hint
            Left = 5,     // left-side hint
            Right = 6     // right-side hint
        }

        // Lowercase #fdm_edge vocabulary, indexed by (int)EdgeTag — matches SectionBlueprint XML doc vocab.
        private static readonly string[] EdgeTagVocab =
            { "wall", "doorway", "open", "window", "back", "left", "right" };

        private static string EdgeTagWord(EdgeTag t)
        {
            int i = (int)t;
            return (i >= 0 && i < EdgeTagVocab.Length) ? EdgeTagVocab[i] : "wall";
        }

        // Per-tag color for an edge sphere so an admin reads the face state at a glance. Opaque + bright (these are
        // solid spheres tinting an opaque vanilla material, not the old translucent quads).
        private static Color EdgeTagColor(EdgeTag t)
        {
            switch (t)
            {
                case EdgeTag.Doorway: return new Color(0.2f, 1f, 0.35f, 1f);  // green = passable
                case EdgeTag.Open:    return new Color(0.3f, 0.8f, 1f, 1f);   // sky-blue = wide open
                case EdgeTag.Window:  return new Color(1f, 0.9f, 0.25f, 1f);  // amber
                case EdgeTag.Back:    return new Color(0.7f, 0.3f, 1f, 1f);   // purple
                case EdgeTag.Left:    return new Color(1f, 0.55f, 0.2f, 1f);  // orange
                case EdgeTag.Right:   return new Color(1f, 0.85f, 0.85f, 1f); // pale (Right pairs with Window amber)
                default:              return new Color(0.95f, 0.4f, 0.25f, 1f); // wall = warm orange-red (clearly "solid")
            }
        }

        #endregion

        #region Unity lifecycle

        private void Awake()
        {
            m_nview = GetComponent<ZNetView>();

            // Placement-math collider: vanilla Player.UpdatePlacementGhost computes the ghost's snap offset from the
            // closest point on a NON-trigger, enabled, convex collider (assembly_valheim/Player.cs ~2716-2745). A
            // trigger-only box leaves that offset at ZERO, and the ghost position collapses to (2*aimPoint + normal*50)
            // — the box lands at ~double the aim coordinates, ~225m away (the "origin/offset placement" bug). So the
            // build box MUST be a SOLID (isTrigger=false) BoxCollider. It rides the 'piece_nonsolid' layer, which is in
            // m_placeRayMask AND m_interactMask (so the place-ray + hover both hit it) but does NOT physically block the
            // player — exactly the behaviour an editor footprint wants.
            m_trigger = GetComponent<BoxCollider>();
            if (m_trigger == null) m_trigger = gameObject.AddComponent<BoxCollider>();
            // GHOST: SOLID (non-trigger) collider — vanilla's placement snap-offset needs it (a trigger-only ghost
            // mis-places, the origin/offset bug). PLACED: a TRIGGER, so the box body never blocks the hammer's
            // place-ray — piece_nonsolid is in Player.m_placeRayMask, and these boxes are platforms to build WITHIN.
            // Valheim runs queriesHitTriggers=false so the place-ray skips the trigger; the context menu resolves a
            // click via ContainsPoint + the orb/wall marker tests, not this collider (so no interaction is lost).
            m_trigger.isTrigger = !Player.IsPlacementGhost(gameObject);
            m_trigger.size = BoxSize;
            int pieceNonsolid = LayerMask.NameToLayer("piece_nonsolid");
            if (pieceNonsolid >= 0) gameObject.layer = pieceNonsolid;

            if (m_nview != null && m_nview.GetZDO() != null)
                LoadFromZDO();

            // Derive box height from the story count (FloorOffset + Stories*StoryHeight), migrating older 4m boxes to
            // the 5m one-story height so a snapped floor + a full story + a compensated doorway always fit.
            BoxSize.y = BoxHeightForStories(Stories);

            ApplyTriggerBounds();

            // Safety net for the "_Copy" material swap: the ObjectDB.Awake prefab-level swap can run before the shared
            // VanillaAssetResolver cache is warm (its harvest source, ZNetScene, may not be populated yet on that one
            // attempt). Re-apply the swap on the PLACED instance — by Awake-on-spawn the cache is warm — so every frame
            // + marker renderer lands on the LIVE vanilla material instead of staying on "<vanilla>_Copy" or NULL.
            ResolveInstanceMaterials();

            // P3: bind the BAKED tag gizmos (wirebox + spheres) + the singleton scroll-cycle driver.
            BindBakedVisual();
            UpdateMarkerTransforms();
            RefreshEdgeMarkerColors();
            FootprintTagScaler.EnsureExists();

            // P5: floor-grid + edge snap-point children (client-only; no-op headless).
            RebuildSnapPoints();

            // WYSIWYG guide walls: build the blue wall/door/window panels for the current tags + hand the orbs of
            // materialized faces off to their walls (an Open face keeps its orb). Client-only; skipped on the ghost.
            RebuildGuides();

            // Register in the live list the context-menu marker source iterates to ray-test every footprint's five
            // spheres, and ensure the Core provider + marker source are registered (idempotent, client-only). This is
            // the SAME mechanism the patrol-node menu uses: Shift+Alt right-click a sphere from a distance opens it.
            // Only real placed instances (valid ZNetView, not a placement ghost) join the live list — a ghost would
            // pollute the ray-test with a phantom footprint that snaps to the cursor every frame.
            if (!IsClientOnly() && !Player.IsPlacementGhost(gameObject))
            {
                if (!Active.Contains(this)) Active.Add(this);
                SectionFootprintContextProvider.EnsureRegistered();
                // Edit-in-Box: if the bench armed a section, this freshly-placed footprint becomes that box (filled).
                // DEFER to a couple frames — doing Instantiate/config inside Awake is unreliable (ZNetView ownership +
                // the final transform aren't settled yet), which is why the box came out empty.
                if (FiresDungeonMaster.Sections.SectionEditSpawner.HasPending)
                {
                    Debug.Log("[FiresDungeonMaster][EDIT-DBG] footprint placed with a pending edit — applying in 2 frames.");
                    StartCoroutine(ApplyPendingEditDeferred());
                }
            }

            DumpFootprintDiagnostics();
        }

        // Re-run the vanilla-material swap on THIS placed instance (warm the resolver first if needed, then Both =
        // material "_Copy"->vanilla + orphaned-shader swap). Then fill any remaining NULL material slot with the LIVE
        // vanilla "stone" base so a frame renderer that baked with an empty slot still renders real stone (the rebake
        // removes those NULL slots; this is defense-in-depth). Client-only (no graphics on a dedi).
        private void ResolveInstanceMaterials()
        {
            if (IsClientOnly()) return;
            try
            {
                if (!FiresCore.Services.VanillaAssetResolver.IsWarmed)
                    FiresCore.Services.VanillaAssetResolver.Warm();
                FiresCore.Services.VanillaAssetResolver.ApplyToPrefab(
                    gameObject, FiresCore.Services.VanillaAssetResolver.AssetSwapMode.Both);

                Material stone = null;
                FiresCore.Services.VanillaAssetResolver.TryResolveMaterial("stone", out stone);
                if (stone != null) FillNullMaterialSlots(stone);
                else FiresCore.Services.VanillaAssetResolver.FixNullMaterials(gameObject);
            }
            catch (System.Exception ex) { Debug.LogWarning($"[FOOTPRINT-DBG] instance material resolve failed: {ex.Message}"); }
        }

        // Replace any NULL slot in every child renderer's shared-material array with the given vanilla material.
        private void FillNullMaterialSlots(Material fill)
        {
            foreach (var mr in GetComponentsInChildren<MeshRenderer>(true))
            {
                var mats = mr.sharedMaterials;
                bool changed = false;
                for (int i = 0; i < mats.Length; i++)
                    if (mats[i] == null) { mats[i] = fill; changed = true; }
                if (changed) mr.sharedMaterials = mats;
            }
        }

        // Concise one-line placement trace (placement works now). GHOST vs PLACED: a placement ghost has an
        // invalid ZNetView and is moved every frame, so its Awake position is meaningless; a placed instance has a
        // valid ZNetView whose ZDO position is the real spot. WireBox=NULL means the bundle wasn't re-baked.
        private void DumpFootprintDiagnostics()
        {
            if (IsClientOnly()) return;
            bool bound = m_wireBox != null;
            Debug.Log($"[FOOTPRINT-DBG] pos={transform.position} BoxSize={BoxSize} valid={(m_nview != null && m_nview.IsValid())} ghost={Player.IsPlacementGhost(gameObject)} wirebox={(bound ? "bound" : "NULL(rebake?)")}");
        }

        private void LateUpdate()
        {
            // Keep the edge quads + center sphere pinned to the (possibly rescaled) footprint faces. NO hover
            // feedback: the crosshair is already the pick indicator, so the spheres never resize or over-glow on aim.
            if (m_markersBuilt) UpdateMarkerTransforms();
        }

        private void OnDestroy()
        {
            Active.Remove(this);
            if (m_guideRoot != null) { SectionGuideWalls.Clear(m_guideRoot.transform); Destroy(m_guideRoot); }
            if (m_markerRoot != null) Destroy(m_markerRoot);
        }

        #endregion

        #region P3 markers (client-only)

        // Build-space palette + sphere geometry. Applied to the LIVE vanilla material the ObjectDB.Awake swap put
        // on each renderer (we instance + tint it — never a fresh Unlit/bundle material, which rendered invisible).
        // Frame + floor read as one teal volume; the four edge spheres glow per-tag (EdgeTagColor); the center is
        // a distinct magenta so the role/save anchor never reads as an edge.
        private static readonly Color FrameColor = new Color(0.15f, 0.85f, 0.95f, 1f);   // cyan/teal frame + floor
        private static readonly Color FrameEmission = new Color(0.10f, 0.55f, 0.65f, 1f);
        private static readonly Color CenterColor = new Color(1f, 0.25f, 0.85f, 1f);     // magenta center
        private static readonly Color CenterEmission = new Color(0.70f, 0.10f, 0.55f, 1f);
        // The baked FootprintSphere mesh is radius 0.8 (diameter 1.6m) at localScale=1, which read far too big in
        // game. Scale each sphere down to ~0.5m — the same handle size the env box uses (Vector3.one * 0.5f). The
        // baked SphereCollider (radius 0.8) scales with the GameObject, so the pick surface tracks the visual.
        private const float SphereDiameter = 0.32f;          // 1.6m baked * 0.32 ≈ 0.5m visual handle
        // Edge spheres sit at mid box height (level with the player's natural aim line at the room edge). Vanilla
        // hover resolves them because they protrude outside the solid box wall (see EdgeMarkerLocal); the aimed-
        // sphere highlight ray-test (RaycastMarker) additionally biases a genuine sphere hit slightly closer so it
        // wins the highlight over a co-located box face in the strict-'<' compare — see MarkerPickBias.
        private const float MarkerGroundY = 0.5f;            // edge-sphere height above the floor top (Y=0)
        private const float EmissionGain = 1.6f;            // push tag colors into a glow on the vanilla material

        /// <summary>Resolve which face/center a hovered collider belongs to. Returns None when not a tag marker.</summary>
        internal MarkerHit ResolveMarker(Collider hit)
        {
            if (hit == null) return MarkerHit.None;
            var go = hit.gameObject;
            if (go == m_markerN) return MarkerHit.North;
            if (go == m_markerE) return MarkerHit.East;
            if (go == m_markerS) return MarkerHit.South;
            if (go == m_markerW) return MarkerHit.West;
            if (go == m_markerCenter) return MarkerHit.Center;
            return MarkerHit.None;
        }

        public enum MarkerHit { None, North, East, South, West, Center }

        private void EnsureMarkers() => BindBakedVisual();

        // Bind the BAKED visual children from the prefab's "FootprintTagMarkers" holder (single source of truth).
        // Fails soft when the holder is absent (a not-yet-rebaked bundle) so there is no NRE — the visual is simply
        // absent until the re-baked bundle + DLL land.
        private void BindBakedVisual()
        {
            if (IsClientOnly()) return;        // headless: tags persist via ZDO, no gizmos
            if (m_markersBuilt) return;

            m_markerRoot = transform.Find("FootprintTagMarkers")?.gameObject;
            if (m_markerRoot == null) return;  // not re-baked yet — fail soft, no NRE

            var r = m_markerRoot.transform;
            m_wireBox      = r.Find("WireBox");
            m_markerFloor  = r.Find("Floor")?.gameObject;
            m_markerN      = r.Find("EdgeMarker_N")?.gameObject;
            m_markerE      = r.Find("EdgeMarker_E")?.gameObject;
            m_markerS      = r.Find("EdgeMarker_S")?.gameObject;
            m_markerW      = r.Find("EdgeMarker_W")?.gameObject;
            m_markerCenter = r.Find("CenterMarker")?.gameObject;
            m_rendN = m_markerN?.GetComponent<MeshRenderer>();
            m_rendE = m_markerE?.GetComponent<MeshRenderer>();
            m_rendS = m_markerS?.GetComponent<MeshRenderer>();
            m_rendW = m_markerW?.GetComponent<MeshRenderer>();
            m_rendCenter = m_markerCenter?.GetComponent<MeshRenderer>();
            m_markersBuilt = true;

            // Interaction is the Core FiresContextMenu (Shift+Alt right-click a sphere): the spheres are picked by
            // SectionFootprintContextProvider's ray-vs-sphere marker source (RaycastMarker), the exact patrol-node
            // path — NO Hoverable and NO solid collider on a sphere. Each sphere gets only a TRIGGER SphereCollider:
            // the context-menu driver's Physics.RaycastAll uses QueryTriggerInteraction.Ignore so it never sees these
            // (the marker source alone resolves the sphere, so it always wins — exactly like a collider-less patrol
            // node), while FootprintTagScaler's raycast uses QueryTriggerInteraction.Collide so Shift+Scroll on a
            // sphere still resolves via ResolveMarker(collider).
            EnsureTriggerCollider(m_markerN);
            EnsureTriggerCollider(m_markerE);
            EnsureTriggerCollider(m_markerS);
            EnsureTriggerCollider(m_markerW);
            EnsureTriggerCollider(m_markerCenter);

            TintBaseVisual();
        }

        // Ensure a sphere carries a TRIGGER SphereCollider (for the Shift+Scroll quick-cycle path only). Trigger =
        // invisible to the context-menu driver's QueryTriggerInteraction.Ignore raycast, so it never competes with
        // the ray-vs-sphere marker source. Idempotent.
        private static void EnsureTriggerCollider(GameObject sphere)
        {
            if (sphere == null) return;
            var col = sphere.GetComponent<SphereCollider>() ?? sphere.AddComponent<SphereCollider>();
            col.isTrigger = true;
        }

        // Tint the always-on geometry ONCE: the wireframe frame + the solid floor read as one teal build volume,
        // the center sphere as magenta. The edge spheres are tinted separately in RefreshEdgeMarkerColors (their
        // color encodes the per-face tag). Tints the LIVE vanilla material the ObjectDB.Awake swap installed —
        // instanced + emissive — which is the proven render path; a fresh Unlit/bundle material was invisible.
        private void TintBaseVisual()
        {
            if (m_baseTinted) return;
            if (m_wireBox != null)
                foreach (var mr in m_wireBox.GetComponentsInChildren<MeshRenderer>(true))
                    ApplyEmissiveTint(mr, FrameColor, FrameEmission);
            // FLOOR: the baked slab's vanilla stone TEXTURE tiles wrong on a resized footprint (the UV is raw mesh
            // UV, so a stretched X/Z scale smears the tiling). Give the floor a fresh SOLID-COLOR material instead —
            // no _MainTex means no UV problem — copying the env-box CreateBoxMaterial recipe (a new Standard material
            // with only _Color set). Standard instanced at runtime renders reliably, exactly like the env markers.
            if (m_markerFloor != null)
                foreach (var mr in m_markerFloor.GetComponentsInChildren<MeshRenderer>(true))
                    mr.material = CreateSolidColorMaterial(FloorColor);
            ApplyEmissiveTint(m_rendCenter, CenterColor, CenterEmission);
            m_baseTinted = true;
        }

        // Solid, single-color floor tint (no texture = no tiling). Teal to read as one build volume with the frame.
        private static readonly Color FloorColor = new Color(0.13f, 0.55f, 0.62f, 1f);

        // Copy of EnvironmentBoxController.CreateBoxMaterial for an OPAQUE solid color: a fresh material whose only
        // set property is _Color (never _MainTex), so the surface renders a flat color with no UV/tiling artifact.
        // Prefers Standard (opaque, lit, renders reliably at runtime); falls back through the same chain the env box
        // uses if Standard is unavailable.
        private static Material CreateSolidColorMaterial(Color color)
        {
            Shader shader = Shader.Find("Standard")
                            ?? Shader.Find("Sprites/Default")
                            ?? Shader.Find("UI/Default")
                            ?? Shader.Find("Legacy Shaders/Diffuse");
            if (shader == null) return null;

            var mat = new Material(shader);
            if (mat.HasProperty("_Color")) mat.SetColor("_Color", color); else mat.color = color;
            return mat;
        }

        // Tint that STAYS on the proven render path: instance the renderer's CURRENT material (the LIVE vanilla
        // material the ObjectDB.Awake VanillaAssetResolver swap put there — the same material that makes the crypt
        // rooms render) and set _Color + a glowing _EmissionColor on it. Never builds a fresh Unlit/bundle material
        // (that path is what the "invisible in-game" report blamed). Assigning mr.material forces an instance, so
        // each renderer gets its own tint without touching the shared swapped material.
        private static void ApplyEmissiveTint(MeshRenderer mr, Color color, Color emission)
        {
            if (mr == null) return;
            var m = mr.material; // instance
            if (m.HasProperty("_Color")) m.SetColor("_Color", color); else m.color = color;
            if (m.HasProperty("_EmissionColor"))
            {
                m.SetColor("_EmissionColor", emission);
                m.EnableKeyword("_EMISSION");
            }
        }

        // RESCALE the baked wirebox + REPOSITION the 5 spheres. The four edge spheres sit at the face midpoints
        // pushed OUTWARD clear of the solid box wall; the center sphere floats above the box roof (see
        // EdgeMarkerLocal / CenterMarkerLocal for why they must protrude). All LOCAL space, so the layout tracks
        // BoxSize on resize.
        private void UpdateMarkerTransforms()
        {
            if (m_markerRoot == null) return;
            Vector3 half = BoxSize / 2f;
            if (m_wireBox != null)
            {
                // baked default 8x4x8; never scale an axis to 0 (a zero scale makes the whole frame invisible).
                Vector3 wbScale = new Vector3(BoxSize.x / 8f, BoxSize.y / 4f, BoxSize.z / 8f);
                wbScale.x = Mathf.Max(wbScale.x, 0.01f);
                wbScale.y = Mathf.Max(wbScale.y, 0.01f);
                wbScale.z = Mathf.Max(wbScale.z, 0.01f);
                m_wireBox.localScale = wbScale;
            }
            if (m_markerFloor != null)
            {
                // Baked floor is an 8x0.1x8 slab with its top face at Y=0; scale X/Z with the box, keep slab depth.
                var f = m_markerFloor.transform;
                f.localScale = new Vector3(Mathf.Max(BoxSize.x / 8f, 0.01f), 1f, Mathf.Max(BoxSize.z / 8f, 0.01f));
                f.localPosition = Vector3.zero;
            }

            Vector3 s = Vector3.one * SphereDiameter;
            SetMarker(m_markerN, EdgeMarkerLocal(0), s);
            SetMarker(m_markerE, EdgeMarkerLocal(1), s);
            SetMarker(m_markerS, EdgeMarkerLocal(2), s);
            SetMarker(m_markerW, EdgeMarkerLocal(3), s);
            SetMarker(m_markerCenter, CenterMarkerLocal(), s);
        }

        private static void SetMarker(GameObject m, Vector3 localPos, Vector3 scale)
        {
            if (m != null) { m.transform.localPosition = localPos; m.transform.localScale = scale; }
        }

        // Sphere local positions. The footprint BODY is a SOLID BoxCollider on the same interact layer as the
        // spheres, so a sphere sitting INSIDE the box would be shadowed by the nearer box wall in vanilla's
        // distance-sorted hover raycast (Player.FindHoverObject) and the box body would win the hover — the sphere
        // [E] would never fire. So the spheres PROTRUDE clear of the box surface: each edge sphere is pushed
        // OUTWARD past its face along the face normal by the sphere's world radius (+ a small margin), and the
        // center sphere floats just above the box roof. The crosshair then hits the exposed sphere collider first.
        private float MarkerGap => (SphereDiameter * BakedSphereRadius) + 0.15f;  // world radius of the scaled sphere + margin
        private const float BakedSphereRadius = 0.8f;                              // FootprintSphere.asset mesh radius at scale 1

        private Vector3 EdgeMarkerLocal(int face)
        {
            // Face midpoint (at mid box height), then push out along the outward face normal so the sphere clears
            // the solid box wall. Mid-height keeps it on the player's natural aim line at the room edge.
            Vector3 mid = EdgeLocalMidpoint(face);            // Y = 0 (box center height in local marker space)
            Vector3 outward = EdgeLocalNormal(face) * MarkerGap;
            return new Vector3(mid.x + outward.x, MarkerGroundY, mid.z + outward.z);
        }

        // Center sphere floats just above the box ROOF (BoxSize.y + gap): the whole-section handle sits ON TOP of the
        // box so it stays reachable even with all four guide walls up (a mid-height orb would be shadowed by a wall's
        // collider in the right-click ray). Was BoxSize.y/2 (mid-height) — the "floating too high yet unreachable" bug.
        private Vector3 CenterMarkerLocal() => new Vector3(0f, BoxSize.y + MarkerGap, 0f);

        /// <summary>World position of an edge sphere (face midpoint, just above the floor), for the cursor ray hit-test.</summary>
        internal Vector3 EdgeMarkerWorld(int face) => transform.TransformPoint(EdgeMarkerLocal(face));

        /// <summary>World position of the center sphere, for the cursor ray hit-test.</summary>
        internal Vector3 CenterMarkerWorld() => transform.TransformPoint(CenterMarkerLocal());

        /// <summary>Close-range pick radius floor for the cursor ray vs a sphere — generous vs the visual diameter.</summary>
        internal float MarkerPickRadius => SphereDiameter * 2.2f;

        // The orbs protrude OUTSIDE the box (edge orbs push out past the wall, the center floats above the roof), so
        // a missed orb pick sends the ray straight past into empty background — nothing to hit. A fixed 0.48m world
        // radius only subtends a workable angle up close (~13° at 2m but ~1.4° at 20m), which is why picking felt
        // limited to a couple metres. So the pick radius GROWS with camera distance as a ~4° cone up to MaxPickRange:
        // aiming near an orb from ~20-30m now selects it, while footprints past the range aren't grabbed by the cone.
        private const float PickAngularSlope = 0.11f;   // ~6.3° half-cone (≈2.2m pick radius at 20m) — easier orb picks
        private const float MaxPickRange = 36f;         // don't select a footprint orb beyond this range

        // Distance-scaled pick radius for one orb; 0 = don't consider it (behind the camera or beyond MaxPickRange).
        private float PickRadiusFor(Ray ray, Vector3 worldPos)
        {
            float dist = Vector3.Dot(worldPos - ray.origin, ray.direction);   // distance along the ray
            if (dist < 0f || dist > MaxPickRange) return 0f;
            return Mathf.Max(MarkerPickRadius, dist * PickAngularSlope);
        }

        // A low sphere sits INSIDE the footprint's solid placement box, so the Core driver's physics ray also hits
        // the box wall at a near-identical distance and — with its strict 'mt.Distance < bestDist' compare — the box
        // would win the tie and the marker would never be selected (the dead-menu root cause). We report the sphere
        // hit a fixed bias CLOSER so a genuine sphere pick always beats the co-located box face. Bias is well under
        // the inter-sphere spacing, so it never makes a sphere win when the cursor isn't actually on it.
        private const float MarkerPickBias = 0.75f;

        // Map the 4 faces (N,E,S,W) onto the MarkerHit enum for the context menu.
        private static readonly MarkerHit[] FaceMarker =
            { MarkerHit.North, MarkerHit.East, MarkerHit.South, MarkerHit.West };

        /// <summary>
        /// Ray-test the 5 marker spheres of this footprint (the driver's cursor ray can't physics-hit them since
        /// they ride the footprint box's collider). Returns the nearest sphere hit + its world distance, or None.
        /// </summary>
        internal MarkerHit RaycastMarker(Ray ray, out float distance)
        {
            distance = float.MaxValue;
            MarkerHit best = MarkerHit.None;
            // Don't gate on m_markersBuilt: the sphere world positions are pure transform math (no baked visual
            // needed), so an admin can still pick + tag a footprint whose gizmo holder hasn't been re-baked yet.

            for (int face = 0; face < FaceCount; face++)
            {
                Vector3 w = EdgeMarkerWorld(face);
                float r = PickRadiusFor(ray, w);
                if (r > 0f && RaySphere(ray, w, r, out float d) && d < distance)
                    { distance = d; best = FaceMarker[face]; }
            }
            Vector3 cw = CenterMarkerWorld();
            float rc = PickRadiusFor(ray, cw);
            if (rc > 0f && RaySphere(ray, cw, rc, out float dc) && dc < distance)
                { distance = dc; best = MarkerHit.Center; }

            // Guide walls (ray-vs-box). A materialized face (tag != Open) has a COLLIDER-LESS guide wall whose orb is
            // hidden, so ray-test the wall's local box directly — aiming anywhere on a wall selects that face. Done in
            // footprint-local space (scale 1, so local distance == world distance).
            Ray local = new Ray(transform.InverseTransformPoint(ray.origin), transform.InverseTransformDirection(ray.direction));
            for (int face = 0; face < FaceCount; face++)
            {
                if (GetEdgeTag(face) == EdgeTag.Open) continue;
                if (RayLocalWallBox(local, face, out float dw) && dw < distance)
                    { distance = dw; best = FaceMarker[face]; }
            }

            // Report the hit a fixed bias closer so the marker beats a co-located physics hit (floor/terrain) in the
            // driver's strict-'<' compare (see MarkerPickBias). Clamped so it never goes behind the camera.
            if (best != MarkerHit.None) distance = Mathf.Max(0f, distance - MarkerPickBias);
            return best;
        }

        // Wall thickness must match SectionGuideWalls.WallThickness so the pick box lines up with the drawn panel.
        private const float GuideWallThickness = 0.5f;

        // Ray (in FOOTPRINT-LOCAL space) vs a face's guide-wall box. Boxes match SectionGuideWalls.BuildFace: N/S span
        // BoxSize.x wide at Z=±(hz - T/2); E/W span BoxSize.z deep at X=±(hx - T/2); all Y in [0, BoxSize.y].
        private bool RayLocalWallBox(Ray local, int face, out float dist)
        {
            float hx = BoxSize.x * 0.5f, hz = BoxSize.z * 0.5f, H = BoxSize.y, T = GuideWallThickness;
            Vector3 c, e;
            switch (face)
            {
                case 0: c = new Vector3(0f, H * 0.5f, hz - T * 0.5f); e = new Vector3(hx, H * 0.5f, T * 0.5f); break;   // N
                case 1: c = new Vector3(hx - T * 0.5f, H * 0.5f, 0f); e = new Vector3(T * 0.5f, H * 0.5f, hz); break;   // E
                case 2: c = new Vector3(0f, H * 0.5f, -(hz - T * 0.5f)); e = new Vector3(hx, H * 0.5f, T * 0.5f); break; // S
                default: c = new Vector3(-(hx - T * 0.5f), H * 0.5f, 0f); e = new Vector3(T * 0.5f, H * 0.5f, hz); break; // W
            }
            return RayAABB(local, c - e, c + e, out dist);
        }

        // Slab-method ray vs AABB; dist = entry distance (>= 0). False if missed or the box is behind the origin.
        private static bool RayAABB(Ray r, Vector3 min, Vector3 max, out float dist)
        {
            dist = 0f;
            float tmin = 0f, tmax = float.MaxValue;
            for (int a = 0; a < 3; a++)
            {
                float o = r.origin[a], d = r.direction[a];
                if (Mathf.Abs(d) < 1e-6f) { if (o < min[a] || o > max[a]) return false; }
                else
                {
                    float inv = 1f / d;
                    float t1 = (min[a] - o) * inv, t2 = (max[a] - o) * inv;
                    if (t1 > t2) { float tmp = t1; t1 = t2; t2 = tmp; }
                    tmin = Mathf.Max(tmin, t1);
                    tmax = Mathf.Min(tmax, t2);
                    if (tmin > tmax) return false;
                }
            }
            dist = tmin;
            return true;
        }

        /// <summary>
        /// Nearest of the 5 marker spheres to a world point — used by the context provider's PHYSICS-hit fallback
        /// path: when the driver's Physics.RaycastAll lands on the footprint's own box collider (not a sphere via the
        /// ray-vs-sphere marker source), we map that hit point to whichever sphere it's closest to so aiming anywhere
        /// on the section still opens the right menu. Center is compared on equal footing with the four edges.
        /// </summary>
        internal MarkerHit NearestMarkerTo(Vector3 worldPoint)
        {
            MarkerHit best = MarkerHit.Center;
            float bestSq = (CenterMarkerWorld() - worldPoint).sqrMagnitude;
            for (int face = 0; face < FaceCount; face++)
            {
                float sq = (EdgeMarkerWorld(face) - worldPoint).sqrMagnitude;
                if (sq < bestSq) { bestSq = sq; best = FaceMarker[face]; }
            }
            return best;
        }

        // Standard ray-vs-sphere; ScreenPointToRay direction is unit so the returned t is world distance.
        private static bool RaySphere(Ray ray, Vector3 center, float radius, out float dist)
        {
            dist = 0f;
            Vector3 oc = ray.origin - center;
            float b = Vector3.Dot(oc, ray.direction);
            float c = Vector3.Dot(oc, oc) - radius * radius;
            float disc = b * b - c;
            if (disc < 0f) return false;
            float sq = Mathf.Sqrt(disc);
            float t = -b - sq;
            if (t < 0f) t = -b + sq;
            if (t < 0f) return false;
            dist = t;
            return true;
        }

